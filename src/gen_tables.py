"""Generate the wavetable ROM and the note-increment table.

Run from the project root:  python src/gen_tables.py
Outputs: src/wavetable_rom.v, src/note_inc.v

Sample rate is 46875 Hz (27 MHz / 18 / 32), matching pt8211_tx.
"""

import math
import os

N = 256            # points per table
BANKS = 4
SCALE = 16384      # half of 16-bit full scale, leaves headroom for 8 voices
FS = 46875.0

# Harmonic amplitudes for each timbre (index 0 = fundamental).
TIMBRES = {
    "sine":    [1.0],
    "guzheng": [1.0, 0.55, 0.34, 0.24, 0.17, 0.11, 0.07, 0.04],
    "pipa":    [1.0, 0.80, 0.62, 0.47, 0.34, 0.24, 0.16, 0.11, 0.07, 0.05, 0.03],
    "organ":   [1.0, 0.00, 0.36, 0.00, 0.22, 0.00, 0.15, 0.00, 0.11, 0.00, 0.07],
}
ORDER = ["sine", "guzheng", "pipa", "organ"]


def build_table(amps):
    raw = []
    for i in range(N):
        ph = 2.0 * math.pi * i / N
        raw.append(sum(a * math.sin(k * ph) for k, a in enumerate(amps, start=1)))
    peak = max(abs(x) for x in raw)
    return [int(round(x / peak * SCALE)) for x in raw]


def emit_wavetable(path):
    lines = [
        "// wavetable_rom.v - generated by src/gen_tables.py, do not edit",
        "// 4 banks x 256 points x signed 16-bit, peak = half full scale",
        "`default_nettype none",
        "",
        "module wavetable_rom (",
        "    input  wire        clk,",
        "    input  wire [1:0]  bank,",
        "    input  wire [7:0]  idx,",
        "    output reg  signed [15:0] data",
        ");",
        "",
        "    reg signed [15:0] rom [0:1023];",
        "",
        "    initial begin",
    ]
    for b, name in enumerate(ORDER):
        vals = build_table(TIMBRES[name])
        lines.append(f"        // bank {b} : {name}")
        for i, v in enumerate(vals):
            lit = f"-16'sd{abs(v)}" if v < 0 else f"16'sd{v}"
            lines.append(f"        rom[{b*256 + i:4d}] = {lit};")
    lines += [
        "    end",
        "",
        "    always @(posedge clk) begin",
        "        data <= rom[{bank, idx}];",
        "    end",
        "",
        "endmodule",
        "",
        "`default_nettype wire",
        "",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def emit_note_inc(path):
    # note index 0..35 -> MIDI 48..83 (C3..B5); index 36..63 = rest
    lines = [
        "// note_inc.v - generated by src/gen_tables.py, do not edit",
        "// inc = f_note * 2^24 / 46875, note index 0..35 = MIDI 48..83 (C3..B5)",
        "`default_nettype none",
        "",
        "module note_inc (",
        "    input  wire [5:0]  note,",
        "    output reg  [23:0] inc",
        ");",
        "",
        "    always @(*) begin",
        "        case (note)",
    ]
    for n in range(36):
        midi = 48 + n
        f = 440.0 * (2.0 ** ((midi - 69) / 12.0))
        val = int(round(f * (1 << 24) / FS))
        lines.append(f"            6'd{n:<2d} : inc = 24'd{val};   // MIDI {midi}  {f:7.2f} Hz")
    lines += [
        "            default: inc = 24'd0;   // rest",
        "        endcase",
        "    end",
        "",
        "endmodule",
        "",
        "`default_nettype wire",
        "",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    emit_wavetable(os.path.join(here, "wavetable_rom.v"))
    emit_note_inc(os.path.join(here, "note_inc.v"))
    print("generated wavetable_rom.v and note_inc.v")
